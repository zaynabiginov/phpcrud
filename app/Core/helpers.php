function base_href(): string
{
    static $base = null;
    if ($base !== null) return $base;

    $script = str_replace('\\', '/', (string) ($_SERVER['SCRIPT_NAME'] ?? ''));
    $scriptName = basename($script);
    $dir = $scriptName !== '' && str_contains($script, '/' . $scriptName)
        ? substr($script, 0, -strlen($scriptName))
        : '/';
    $dir = '/' . trim($dir, '/');
    if ($dir !== '/') $dir .= '/';

    return $base = $dir;
}

function url(string $path = ''): string
{
    return base_href() . ltrim($path, '/');
}

function e($value): string
{
    return htmlspecialchars((string) ($value ?? ''), ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

function db_text($value): string
{
    $s = (string) ($value ?? '');
    if ($s === '') return $s;
    $ok_cyr = static fn(string $x): bool => (bool) preg_match('/[А-Яа-яЁё]/u', $x);
    $is_bad = static fn(string $x): bool =>
        (bool) preg_match('/Ã.|Â.|â€|Ð[\x80-\xBF]|Ñ[\x80-\xBF]/u', $x)
        || ((bool) preg_match('/Р[\x80-\xBF]/u', $x) && !preg_match('/[А-Яа-яЁё]{2}/u', $x));
    if (preg_match('//u', $s) && $ok_cyr($s) && !$is_bad($s)) return $s;
    $cur = $s;
    for ($i = 0; $i < 6; $i++) {
        if (!preg_match('//u', $cur) || !$is_bad($cur)) break;
        $bytes = @mb_convert_encoding($cur, 'Windows-1252', 'UTF-8');
        if (!is_string($bytes) || $bytes === '' || $bytes === $cur) break;
        $cur = $bytes;
        if (preg_match('//u', $cur) && $ok_cyr($cur) && !$is_bad($cur)) return $cur;
    }
    if (preg_match('//u', $cur) && $ok_cyr($cur) && !$is_bad($cur)) return $cur;
    foreach (['Windows-1251', 'KOI8-R', 'CP866'] as $enc) {
        $alt = @mb_convert_encoding($s, 'UTF-8', $enc);
        if (is_string($alt) && preg_match('//u', $alt) && $ok_cyr($alt) && !$is_bad($alt)) return $alt;
    }
    return $s;
}

function app_lang(): string
{
    static $lang = null;
    if ($lang !== null) return $lang;
    $allowed = ['ru', 'uz', 'en'];
    $req = strtolower(trim((string) ($_GET['lang'] ?? '')));
    if ($req !== '' && in_array($req, $allowed, true)) {
        $_SESSION['lang'] = $req;
        $secure = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off');
        setcookie('lang', $req, ['expires' => time() + 31536000, 'path' => '/', 'secure' => $secure, 'httponly' => false, 'samesite' => 'Lax']);
        $lang = $req; return $lang;
    }
    $sess = strtolower(trim((string) ($_SESSION['lang'] ?? '')));
    if (in_array($sess, $allowed, true)) { $lang = $sess; return $lang; }
    $cookie = strtolower(trim((string) ($_COOKIE['lang'] ?? '')));
    if (in_array($cookie, $allowed, true)) { $_SESSION['lang'] = $cookie; $lang = $cookie; return $lang; }
    $lang = 'ru'; $_SESSION['lang'] = $lang; return $lang;
}

