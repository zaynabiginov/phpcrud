function fmt_money($n): string { return number_format((float) $n, 2, ',', ' '); }
function fmt_money0($n): string { return number_format((float) $n, 0, ',', ' '); }
function fmt_qty($n): string { $s = number_format((float) $n, 3, ',', ' '); $s = rtrim(rtrim($s, '0'), ','); return $s === '' ? '0' : $s; }
function normalize_unit($u): string { $u = trim((string) $u); return in_array($u, ['шт', 'л', 'кг', 'кв.м'], true) ? $u : 'шт'; }
function allowed_units(): array { return ['шт', 'л', 'кг', 'кв.м']; }
function parse_qty($v): float { $n = (float) str_replace([' ', ','], ['', '.'], (string) $v); return $n < 0 ? 0.0 : round($n, 3); }
function parse_money($v): float { return round((float) str_replace([' ', ','], ['', '.'], (string) $v), 2); }

function get_usd_rate(): array
{
    $cacheKey = 'usd_rate_' . date('Y-m-d');
    if (!empty($_SESSION[$cacheKey]) && is_array($_SESSION[$cacheKey])) {
        return $_SESSION[$cacheKey];
    }
    $result = ['rate' => null, 'date' => null, 'diff' => null];
    try {
        $ctx = stream_context_create(['http' => ['timeout' => 3], 'https' => ['timeout' => 3]]);
        $json = @file_get_contents('https://cbu.uz/uz/arkhiv-kursov-valyut/json/USD/', false, $ctx);
        if ($json) {
            $data = json_decode($json, true);
            if (is_array($data) && isset($data[0]['Rate'])) {
                $result['rate'] = (string) $data[0]['Rate'];
                $result['date'] = (string) ($data[0]['Date'] ?? date('d.m.Y'));
                $result['diff'] = (string) ($data[0]['Diff'] ?? '');
            }
        }
    } catch (\Throwable $e) {
    }
    $_SESSION[$cacheKey] = $result;
    return $result;
}
